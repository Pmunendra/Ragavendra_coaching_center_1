def generate_students_list_pdf(rows, output_path, title="Student List"):
    """rows: list of dicts with keys name, college, email, phone, address,
    registered, exam_count, avg_score, best_score, subscription."""
    doc = SimpleDocTemplate(
        output_path, pagesize=A4,
        topMargin=15 * mm, bottomMargin=15 * mm, leftMargin=12 * mm, rightMargin=12 * mm,
    )
    story = [
        Paragraph("EXAM PORTAL", styles["ReportTitle"]),
        Paragraph(title, styles["Small"]),
        Spacer(1, 10),
    ]

    header = ["Name", "College", "Email", "Phone", "Registered", "Exams", "Avg %", "Best %", "Subscription"]
    data = [header]
    for r in rows:
        data.append([
            r.get("name", ""), r.get("college", "") or "-", r.get("email", ""), r.get("phone", ""),
            r.get("registered", ""), str(r.get("exam_count", 0)),
            str(r.get("avg_score", 0)), str(r.get("best_score", 0)), r.get("subscription", "-"),
        ])

    t = Table(data, repeatRows=1, colWidths=[26 * mm, 26 * mm, 38 * mm, 20 * mm, 18 * mm, 12 * mm, 12 * mm, 12 * mm, 22 * mm])
    t.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, -1), 7.5),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#cccccc")),
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#3f51b5")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f7f8fc")]),
    ]))
    story.append(t)
    story.append(Spacer(1, 8))
    story.append(Paragraph(f"Generated: {datetime.utcnow().strftime('%d %b %Y, %H:%M UTC')} &nbsp;|&nbsp; Total: {len(rows)} student(s)", styles["Small"]))

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return output_path


