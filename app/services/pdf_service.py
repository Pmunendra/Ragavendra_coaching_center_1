def generate_invoice_pdf(purchase, output_path):
    student = purchase.student
    course = purchase.course

    doc = SimpleDocTemplate(
        output_path, pagesize=A4,
        topMargin=18 * mm, bottomMargin=18 * mm, leftMargin=18 * mm, rightMargin=18 * mm,
    )
    story = [
        Paragraph("EXAM PORTAL", styles["ReportTitle"]),
        Paragraph("Payment Invoice", styles["Small"]),
        Spacer(1, 12),
    ]

    info = [
        ["Invoice No.", purchase.invoice_number or "-", "Date", (purchase.verified_at or purchase.created_at).strftime("%d %b %Y")],
        ["Student", student.full_name, "College", student.college_name],
        ["Email", student.email, "Phone", student.phone],
    ]
    t1 = Table(info, colWidths=[28 * mm, 62 * mm, 25 * mm, 55 * mm])
    t1.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cccccc")),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#eeeeee")),
        ("BACKGROUND", (2, 0), (2, -1), colors.HexColor("#eeeeee")),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    story.append(t1)
    story.append(Spacer(1, 12))

    story.append(Paragraph("Course Purchased", styles["SectionHeading"]))
    course_data = [
        ["Course", "Duration", "Amount Paid", "Status", "Reference"],
        [course.title, course.duration_label or "-", f"Rs. {purchase.amount:.2f}",
         purchase.status.upper(), purchase.student_txn_id or purchase.reference_code],
    ]
    t2 = Table(course_data, colWidths=[55 * mm, 30 * mm, 30 * mm, 25 * mm, 30 * mm])
    t2.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cccccc")),
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#3f51b5")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    story.append(t2)
    story.append(Spacer(1, 10))

    # Amount breakdown - only shown when there's something to break down
    # (discount / GST / platform fee), so a plain purchase's invoice stays
    # as simple as before. Mirrors the checkout page breakdown exactly, and
    # is why original_amount/discount_amount/tax_amount/platform_fee_amount
    # are all stored separately on the purchase rather than only the total.
    if (purchase.discount_amount or purchase.tax_amount or purchase.platform_fee_amount):
        story.append(Paragraph("Amount Breakdown", styles["SectionHeading"]))
        breakdown_rows = [["Plan Amount", f"Rs. {(purchase.original_amount or purchase.amount):.2f}"]]
        if purchase.discount_amount:
            coupon_label = f" ({purchase.coupon.code})" if purchase.coupon else ""
            breakdown_rows.append([f"Discount{coupon_label}", f"- Rs. {purchase.discount_amount:.2f}"])
        if purchase.tax_amount:
            breakdown_rows.append(["GST", f"Rs. {purchase.tax_amount:.2f}"])
        if purchase.platform_fee_amount:
            breakdown_rows.append(["Platform / Payment Convenience Fee", f"Rs. {purchase.platform_fee_amount:.2f}"])
        breakdown_rows.append(["Total Paid", f"Rs. {purchase.amount:.2f}"])
        t3 = Table(breakdown_rows, colWidths=[100 * mm, 70 * mm])
        t3.setStyle(TableStyle([
            ("FONTSIZE", (0, 0), (-1, -1), 9),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cccccc")),
            ("ALIGN", (1, 0), (1, -1), "RIGHT"),
            ("FONTNAME", (0, -1), (-1, -1), "Helvetica-Bold"),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ]))
        story.append(t3)
        story.append(Spacer(1, 10))

    if purchase.expires_at:
        story.append(Paragraph(f"Subscription active until: <b>{purchase.expires_at.strftime('%d %b %Y')}</b>", styles["QBody"]))

    story.append(Spacer(1, 20))
    story.append(Paragraph("This is a system-generated invoice.", styles["Small"]))

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return output_path


def generate_certificate_pdf(certificate, output_path):
    """Landscape completion certificate for the Certificates module.
    `certificate` is an IssuedCertificate row (student_account, course set)."""
    from reportlab.pdfgen import canvas as pdf_canvas
    from reportlab.lib.pagesizes import landscape

    student = certificate.student_account
    course = certificate.course

    page_w, page_h = landscape(A4)
    c = pdf_canvas.Canvas(output_path, pagesize=landscape(A4))

    # Border
    c.setStrokeColor(colors.HexColor("#1a237e"))
    c.setLineWidth(3)
    c.rect(12 * mm, 12 * mm, page_w - 24 * mm, page_h - 24 * mm)
    c.setLineWidth(1)
    c.rect(16 * mm, 16 * mm, page_w - 32 * mm, page_h - 32 * mm)

    c.setFont("Helvetica-Bold", 26)
    c.setFillColor(colors.HexColor("#1a237e"))
    c.drawCentredString(page_w / 2, page_h - 40 * mm, "CERTIFICATE OF COMPLETION")

    c.setFont("Helvetica", 12)
    c.setFillColor(colors.HexColor("#555555"))
    c.drawCentredString(page_w / 2, page_h - 52 * mm, "Kalyani Exam Hub proudly presents this certificate to")

    c.setFont("Helvetica-Bold", 30)
    c.setFillColor(colors.HexColor("#000000"))
    c.drawCentredString(page_w / 2, page_h - 68 * mm, student.full_name)

    c.setFont("Helvetica", 13)
    c.setFillColor(colors.HexColor("#333333"))
    c.drawCentredString(
        page_w / 2, page_h - 82 * mm,
        f"for successfully completing the course \"{course.title}\""
    )
    c.drawCentredString(
        page_w / 2, page_h - 90 * mm,
        f"with {certificate.completion_percent:.0f}% of the study material covered."
    )

    c.setFont("Helvetica", 10)
    c.setFillColor(colors.HexColor("#777777"))
    c.drawCentredString(page_w / 2, 32 * mm, f"Certificate No. {certificate.certificate_number}")
    c.drawCentredString(page_w / 2, 26 * mm, f"Issued on {certificate.issued_at.strftime('%d %B %Y')}")

    c.setFont("Helvetica-Bold", 12)
    c.setFillColor(colors.HexColor("#1a237e"))
    c.drawCentredString(page_w / 2, 44 * mm, "Kalyani Exam Hub")

    c.showPage()
    c.save()
    return output_path
